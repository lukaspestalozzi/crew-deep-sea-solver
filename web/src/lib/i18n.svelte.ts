export type Key = keyof (typeof STRINGS)['en'];

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'en' || saved === 'de') return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.startsWith('de') ? 'de' : 'en';
}

class I18n {
  lang = $state<Lang>(initialLang());

  set(lang: Lang) {
    this.lang = lang;
    try {
      localStorage.setItem('lang', lang);
    } catch {
      /* storage unavailable */
    }
  }

  t = (key: Key, params: Record<string, string | number> = {}): string => {
    let s: string = STRINGS[this.lang][key] ?? STRINGS.en[key];
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };

  /** Player name for display: index 0 -> "Player1" / "Spieler1". */
  player = (i: number) => (this.lang === 'de' ? `Spieler${i + 1}` : `Player${i + 1}`);

  /** Owner string from the notation ("Player2", "?", "crew") for display. */
  owner = (o: string) => {
    if (o.startsWith('Player')) return this.player(Number(o.slice(6)) - 1);
    if (o === 'crew') return this.lang === 'de' ? 'Crew' : 'crew';
    return o;
  };
}

